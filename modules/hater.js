function pick(list) {
  return list[Math.floor(Math.random() * list.length)];
}

function choose(pool, key, recent) {
  const source = Array.isArray(pool) && pool.length ? pool : BANKS.generic;
  const used = recent.get(key) || [];
  const candidates = source.filter(line => !used.includes(line));
  const line = pick(candidates.length ? candidates : source);
  used.push(line);
  if (used.length > 8) used.shift();
  recent.set(key, used);
  return line;
}

function getClockState(date = new Date()) {
  const hour = date.getHours();
  if (hour >= 23 || hour < 7) return { period: 'night', sleeping: true };
  if (hour >= 7 && hour < 10) return { period: 'morning', sleeping: false };
  if (hour >= 10 && hour < 17) return { period: 'day', sleeping: false };
  if (hour >= 17 && hour < 21) return { period: 'evening', sleeping: false };
  return { period: 'late', sleeping: false };
}

function countFeatures(text) {
  const t = String(text || '');
  const tests = {
    bold: /\*\*[^*]+\*\*/s,
    italic: /(?<!\*)\*[^*]+\*(?!\*)|(?<!_)_[^_]+_(?!_)/s,
    strike: /~~[^~]+~~/s,
    inlineCode: /`[^`]+`/s,
    codeBlock: /```[\s\S]*?```/,
    quote: /^\s*>/m,
    spoiler: /\|\|[^|]+\|\|/s,
    link: /\[[^\]]+\]\([^)]+\)/,
    list: /^\s*(?:[-*•]|\d+[.)])\s+/m,
    underline: /\+\+[^+]+\+\+/s,
    mark: /==[^=]+==/s,
    color: /\[c:[^\]]+\][\s\S]*?\[\/c\]/i,
    superscript: /\^\^[\s\S]+?\^\^/,
    subscript: /,,[^,]+,,/,
  };
  return Object.entries(tests).filter(([, regex]) => regex.test(t)).map(([name]) => name);
}

function textCategory(text) {
  const t = String(text || '').trim();
  const compact = t.replace(/\s/g, '');
  const letters = Array.from(compact);
  const features = countFeatures(t);
  if (/^\/(?:help|commands|помощь)(?:\s|$)/i.test(t)) return 'help';
  if (/^\/(?:roll|dice|кубик|d)(?:\s|$)/i.test(t)) return 'roll';
  if (/^\/(?:offline|away|afk|оффлайн)(?:\s|$)/i.test(t)) return 'command';
  if (t.startsWith('/')) return 'command';
  if (/^(привет|здравствуй|хай|ку|доброе утро|добрый вечер|добрый день)\b/i.test(t)) return 'greeting';
  if (/^(спасибо|спс|благодарю|thx|thanks)\b/i.test(t)) return 'thanks';
  if (/^(извини|извините|сорри|прости|виноват)\b/i.test(t)) return 'apology';
  if (features.includes('codeBlock') || features.includes('inlineCode')) return features.length > 1 ? 'formatCombo' : 'code';
  if (features.length > 1) return 'formatCombo';
  if (features.length === 1) return 'formatted';
  if (letters.length <= 1) return 'oneSymbol';
  if (letters.length <= 4) return 'tiny';
  if (/^[^a-zа-яё]*[A-ZА-ЯЁ0-9\s!?.,:;_\-—]+$/u.test(t) && /[A-ZА-ЯЁ]/u.test(t)) return 'caps';
  if (letters.length >= 150) return 'long';
  if (/[?？]$/.test(t)) return 'questions';
  if (letters.length <= 18) return 'short';
  if (letters.length > 28 && !/[.!?…,:;]/.test(t)) return 'noPunct';
  return 'generic';
}

